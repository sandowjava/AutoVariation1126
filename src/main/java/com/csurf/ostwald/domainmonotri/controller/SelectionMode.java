/**
 * Defines the available selection modes for color manipulation.
 */
public enum SelectionMode {
    /**
     * Default mode supporting multi-selection for color-dragging and hue-rotation.
     */
    DEFAULT,
    
    /**
     * Single-selection mode for hand-painting colors.
     */
    HAND_PAINT
}
